namespace FantasyTale.Launcher.Sdk;

/// <summary>Optional game-module capability for running a separately installed server package.</summary>
public interface ILocalServerModule
{
    /// <summary>Validates the package and creates a managed-stdio plan without starting a process.</summary>
    LocalServerPlan CreateServerPlan(LocalServerContext context);
}

/// <summary>Saved local hosting choices; they never include account credentials or arbitrary commands.</summary>
/// <param name="Id">Stable local hosting identifier.</param>
/// <param name="Game">Game module owning the server adapter.</param>
/// <param name="Build">Client build accepted by this server.</param>
/// <param name="Name">Room or local server display name.</param>
/// <param name="PackagePath">Directory of the separately installed server package.</param>
/// <param name="Mode">private for loopback, lan for a private interface, or room for publicly advertised hosting.</param>
/// <param name="AdvertisedHost">Address other players can reach in room mode.</param>
/// <param name="GamePort">Game listener port.</param>
/// <param name="ApiPort">Account and discovery listener port.</param>
/// <param name="AdminPort">Loopback-only web administration port.</param>
/// <param name="TemporaryData">Whether the adapter may explicitly select process-local storage.</param>
public sealed record LocalServerProfile(string Id, string Game, string Build, string Name, string PackagePath,
    string Mode, string AdvertisedHost, int GamePort, int ApiPort, int AdminPort, bool TemporaryData)
{
    /// <summary>Match transport listener; null uses the port immediately after the game listener.</summary>
    public int? RelayPort { get; init; }

    /// <summary>Resolved match listener for adapters that provide a separate relay.</summary>
    public int EffectiveRelayPort => RelayPort ?? GamePort + 1;

    /// <summary>Whether players must sign in to the local account service instead of joining by name.</summary>
    public bool RequireAuthentication { get; init; }

    /// <summary>Registered client supplying this build's read-only game data; null allows an installed matching client.</summary>
    public string? ClientInstanceId { get; init; }

    /// <summary>Explicit package, local or temporary storage selection; null preserves the legacy temporary-data choice.</summary>
    public string? StorageMode { get; init; }

    /// <summary>
    /// Resolved storage selection. Launcher single play and rooms save to a local SQLite file unless the player chose
    /// the package's own storage; a dedicated server's own setup still recommends MySQL.
    /// </summary>
    public string EffectiveStorageMode => StorageMode ?? (TemporaryData ? "temporary" : "local");
}

/// <summary>Validated hosting input and the isolated directory where generated launch files belong.</summary>
/// <param name="Game">Installed game definition.</param>
/// <param name="Build">Supported client build definition.</param>
/// <param name="Profile">User's saved server settings.</param>
/// <param name="SessionDirectory">Owned directory for this invocation's generated files.</param>
public sealed record LocalServerContext(GameDefinition Game, BuildDefinition Build, LocalServerProfile Profile, string SessionDirectory)
{
    /// <summary>Verified installed client directory supplying archives without copying or modifying them.</summary>
    public string? ClientDirectory { get; init; }

    /// <summary>Stable, exclusively leased directory for this profile's game data, separate from package and invocation files.</summary>
    public string? DataDirectory { get; init; }
}

/// <summary>One text configuration file generated by a game server adapter.</summary>
/// <param name="Name">Simple file name beneath the invocation directory.</param>
/// <param name="Text">UTF-8 configuration, never a shell script.</param>
public sealed record LocalServerFile(string Name, string Text);

/// <summary>Process description for the private stdin stop and stdout readiness protocol.</summary>
/// <param name="Executable">Absolute executable path inside the selected package.</param>
/// <param name="Arguments">Individual arguments; no shell expansion is performed.</param>
/// <param name="Files">Generated configuration files written before startup.</param>
/// <param name="ApiUrl">Loopback account/discovery URL used by the host player.</param>
/// <param name="AdminUrl">Loopback web administration URL.</param>
public sealed record LocalServerPlan(string Executable, IReadOnlyList<string> Arguments, IReadOnlyList<LocalServerFile> Files,
    string ApiUrl, string AdminUrl)
{
    /// <summary>Adapter-owned process overrides; never exposed in frontend status or logs.</summary>
    public IReadOnlyDictionary<string, string> Environment { get; init; } = new Dictionary<string, string>();
    /// <summary>Maximum time to wait for the server's post-initialization readiness marker.</summary>
    public int StartupSeconds { get; init; } = 90;
    /// <summary>Grace period for stop/EOF before the owned process tree is terminated.</summary>
    public int ShutdownSeconds { get; init; } = 20;
}

/// <summary>Process status exposed to the frontend without private invocation details.</summary>
/// <param name="ProfileId">Saved profile identity.</param>
/// <param name="RunId">Unique invocation identity used to reject stale stop requests.</param>
/// <param name="State">starting, ready, stopping, stopped or failed.</param>
/// <param name="ProcessId">Observed process identifier, not authority to terminate arbitrary processes.</param>
/// <param name="StartedAt">Time the owned process started.</param>
/// <param name="ExitCode">Exit status when known.</param>
/// <param name="Failure">Stable diagnostic code, or null.</param>
/// <param name="ForcedStop">Whether shutdown exhausted its graceful deadline.</param>
/// <param name="ApiUrl">Local account API, available only while ready.</param>
/// <param name="AdminUrl">Local administration URL, available only while ready.</param>
/// <param name="LogPath">Bounded local process log file.</param>
public sealed record LocalServerStatus(string ProfileId, string RunId, string State, int ProcessId, DateTimeOffset StartedAt,
    int? ExitCode, string? Failure, bool ForcedStop, string? ApiUrl, string? AdminUrl, string LogPath);
